"""
Assemble the R^2 matrix from cross-state validate runs generated by
pipeline_configs/generate_cross_state_validate_config.py: rows = the
state the model was trained on, columns = which state's imagery it was
evaluated against, for ONE fixed (--year, --quarter) -- holding season
fixed and varying only geography, the direct geographic counterpart of
build_cross_quarter_r2_matrix.py (which holds state fixed and varies
quarter). Comparing this matrix's off-diagonal R^2 drop against that
one's is how you actually answer "does season or geography hurt transfer
more" instead of eyeballing two differently-shaped outputs.

The diagonal is NOT a cross-state run (generate_cross_state_validate_
config.py deliberately never generates it -- see that script's
docstring): it's each state's own existing per-quarter validate.py
output (epoch*_valset_<own prefix>_preds.csv directly under that state's
ckpt_dir, dataset.new=False, test-only, leak-free) -- the same number
3_validation/validate.py already reports and build_cross_quarter_r2_
matrix.py already uses as ITS diagonal, so both matrices' diagonals for a
shared (state, quarter) cell are identically the same number by
construction, not independently re-measured.

A real, unavoidable asymmetry this introduces: the diagonal is each
state's held-out TEST SPLIT ONLY (~10% of its chips, per generate_train_
config.py's default 0.8/0.1/0.1 split), while every off-diagonal
cross-state cell is the FULL target state's available imagery for that
quarter (dataset.new=True -- see generate_cross_state_validate_config.py
for why: there's no shared-GEOID held-out subset across states to
restrict to, and none is needed since the source model never saw any of
the target state's chips regardless). The off-diagonal cells are each
evaluated on a LARGER, and not necessarily equally-difficult, population
than the diagonal they're being compared against. That's a real
asymmetry to keep in mind reading this matrix -- not a bug, just an
unavoidable consequence of cross-state comparison having no shared-item
space to fall back on the way cross-quarter does.

Doesn't run anything itself -- reads the preds CSVs sail's task: validate
already wrote. A blank cell means that pair hasn't been validated yet --
generate and run that config first (or run generate_validate_config.py
for a missing diagonal), this script doesn't fill in the gaps.

Usage:
    python 3_analysis/build_cross_state_r2_matrix.py \
        --variable wealth_index --year 2016 --quarter 1 \
        --states oh pa az \
        --out-dir ./out_cross_state/2016q1_wealth_index

    # Also bootstrap each cell's R^2 for a CI (same mechanism/caveats as
    # build_cross_quarter_r2_matrix.py's --bootstrap-iters):
    python 3_analysis/build_cross_state_r2_matrix.py \
        --variable wealth_index --year 2016 --quarter 1 \
        --states oh pa az --out-dir ./out_cross_state/2016q1_wealth_index \
        --bootstrap-iters 1000
"""

import argparse
import glob
import os
import sys
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from matplotlib.colors import TwoSlopeNorm
from sklearn.metrics import r2_score

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "pipeline_configs"))
from generate_train_config import load_registry, resolve_state_settings  # noqa: E402
from generate_validate_config import latest_existing_version  # noqa: E402
from generate_cross_state_validate_config import CROSS_STATE_SUBDIR  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_cross_quarter_r2_matrix import bootstrap_r2  # noqa: E402


def state_ckpt_dir(state, variable, year, quarter, version, registry):
    st = resolve_state_settings(state, registry)
    data_root = st["data_root_template"].format(state=state, year=year, quarter=quarter)
    data_root = data_root if data_root.endswith("/") else data_root + "/"
    output_dir = data_root + "artifacts/"
    exp_base = f"{state}_q{quarter}_{year}_{variable}"
    v = version or latest_existing_version(output_dir, exp_base)
    return os.path.join(output_dir, f"{exp_base}_{v}")


def state_prefix(state, variable, year, quarter, registry):
    st = resolve_state_settings(state, registry)
    base_prefix = st["base_prefix_template"].format(state=state, year=year, quarter=quarter)
    return f"{base_prefix}_{variable}"


def find_diagonal_preds_csv(ckpt_dir: str, prefix: str):
    """The state's own leak-free held-out-test preds -- directly under
    ckpt_dir (generate_validate_config.py's normal output, no
    output_subdir), NOT the cross_state/ subfolder. See module docstring."""
    pattern = os.path.join(ckpt_dir, f"epoch*_valset_{prefix}_preds.csv")
    matches = sorted(glob.glob(pattern))
    if len(matches) == 0:
        return None
    if len(matches) > 1:
        print(f"  WARNING: {len(matches)} files match {pattern!r}, using the newest: {matches[-1]}")
    return matches[-1]


def find_cross_state_preds_csv(ckpt_dir: str, prefix: str):
    """A cross-state cell's full-target-dataset preds -- under ckpt_dir/
    cross_state/ (generate_cross_state_validate_config.py's
    output_subdir), dataset.new=True so sail names it epoch*_full_*
    rather than epoch*_valset_*."""
    pattern = os.path.join(ckpt_dir, CROSS_STATE_SUBDIR, f"epoch*_full_{prefix}_preds.csv")
    matches = sorted(glob.glob(pattern))
    if len(matches) == 0:
        return None
    if len(matches) > 1:
        print(f"  WARNING: {len(matches)} files match {pattern!r}, using the newest: {matches[-1]}")
    return matches[-1]


def build_matrix(variable, year, quarter, states, version, registry,
                  bootstrap_iters=0, ci=0.95, seed=1337):
    labels = [s.upper() for s in states]
    n = len(states)
    r2 = pd.DataFrame(np.nan, index=labels, columns=labels)
    n_pairs = pd.DataFrame(0, index=labels, columns=labels, dtype=int)
    bootstrap_rows = []

    ckpt_dirs = {}
    for state in states:
        try:
            ckpt_dirs[state] = state_ckpt_dir(state, variable, year, quarter, version, registry)
        except SystemExit as e:
            print(f"[{state.upper()}] no trained model found, skipping this row entirely: {e}")

    for i, model_state in enumerate(states):
        if model_state not in ckpt_dirs:
            continue
        ckpt_dir = ckpt_dirs[model_state]

        for j, imagery_state in enumerate(states):
            if model_state == imagery_state:
                prefix = state_prefix(imagery_state, variable, year, quarter, registry)
                csv_path = find_diagonal_preds_csv(ckpt_dir, prefix)
                cell_kind = "own held-out test set"
            else:
                # The cross-state prefix only needs imagery_state's
                # registry entry, not a trained model there -- it's
                # ckpt_dir (model_state's) that holds the preds either way.
                prefix = state_prefix(imagery_state, variable, year, quarter, registry)
                csv_path = find_cross_state_preds_csv(ckpt_dir, prefix)
                cell_kind = "full target-state imagery"

            if csv_path is None:
                print(f"[{labels[i]} model on {labels[j]} imagery] not validated yet "
                      f"(expected {cell_kind} preds under {ckpt_dir})")
                continue

            df = pd.read_csv(csv_path)
            y_true = df["label"].to_numpy()
            y_pred = df["pred"].to_numpy()
            score = r2_score(y_true, y_pred)
            r2.iloc[i, j] = score
            n_pairs.iloc[i, j] = len(df)
            marker = " (diagonal)" if i == j else ""

            boot_msg = ""
            if bootstrap_iters > 0:
                boot = bootstrap_r2(y_true, y_pred, bootstrap_iters, ci, seed)
                if boot is None:
                    print(f"  WARNING: every bootstrap resample for {labels[i]} model on "
                          f"{labels[j]} imagery had zero label variance -- skipping CI for this cell")
                else:
                    bootstrap_rows.append({
                        "model_state": labels[i], "imagery_state": labels[j],
                        "r2": score, "n": len(df), **boot,
                    })
                    boot_msg = (f"  {int(ci * 100)}% CI=[{boot['ci_lower']:.4f}, "
                                f"{boot['ci_upper']:.4f}] (n_boot={boot['n_boot']})")

            print(f"[{labels[i]} model on {labels[j]} imagery]{marker} r2={score:.4f} "
                  f"n={len(df)} ({cell_kind}){boot_msg}")

    bootstrap_df = pd.DataFrame(bootstrap_rows)
    return r2, n_pairs, bootstrap_df


def compute_transfer_penalty(r2: pd.DataFrame) -> pd.DataFrame:
    """penalty[i, j] = R^2(j's own diagonal) - R^2(i's model on j's
    imagery) for i != j -- positive means geographic transfer COST
    accuracy relative to j's own model, matching the sign convention
    analyze_cross_quarter_significance.py's delta_r2 uses (just negated,
    so 'penalty' reads positive-is-worse instead of delta reading
    negative-is-worse)."""
    penalty = pd.DataFrame(np.nan, index=r2.index, columns=r2.columns)
    for j in r2.columns:
        diag = r2.loc[j, j]
        if not np.isfinite(diag):
            continue
        for i in r2.index:
            if i == j or not np.isfinite(r2.loc[i, j]):
                continue
            penalty.loc[i, j] = diag - r2.loc[i, j]
    return penalty


def plot_matrix(r2: pd.DataFrame, year: int, quarter: int, variable: str, out_path: str):
    fig, ax = plt.subplots(figsize=(1.2 * len(r2.columns) + 3, 1.2 * len(r2.index) + 3))

    finite = r2.values[np.isfinite(r2.values)]
    if finite.size == 0:
        raise SystemExit("No R^2 values to plot -- run the validate jobs first.")

    vmin, vmax = float(finite.min()), float(finite.max())
    if vmin < 0 < vmax:
        norm = TwoSlopeNorm(vmin=vmin, vcenter=0, vmax=vmax)
    else:
        norm = None

    im = ax.imshow(r2.values, cmap="RdBu", norm=norm,
                    vmin=None if norm else vmin, vmax=None if norm else vmax)

    ax.set_xticks(range(len(r2.columns)))
    ax.set_xticklabels(r2.columns, rotation=45, ha="right")
    ax.set_yticks(range(len(r2.index)))
    ax.set_yticklabels(r2.index)
    ax.set_xlabel("Evaluated on imagery from")
    ax.set_ylabel("Model trained on")
    ax.set_title(f"{year} Q{quarter} {variable}: cross-state R²\n"
                 f"(diagonal = own held-out test set; off-diagonal = full target imagery)")

    for i in range(len(r2.index)):
        for j in range(len(r2.columns)):
            val = r2.iloc[i, j]
            if np.isfinite(val):
                ax.text(j, i, f"{val:.2f}", ha="center", va="center", fontsize=9)
            else:
                ax.text(j, i, "—", ha="center", va="center", fontsize=9, color="gray")

    for i in range(min(len(r2.index), len(r2.columns))):
        ax.add_patch(plt.Rectangle((i - 0.5, i - 0.5), 1, 1, fill=False,
                                    edgecolor="black", linewidth=2))

    fig.colorbar(im, ax=ax, label="R²")
    fig.tight_layout()
    fig.savefig(out_path, dpi=150)
    plt.close(fig)
    print(f"Wrote {out_path}")


def main():
    p = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--variable", required=True)
    p.add_argument("--year", required=True, type=int)
    p.add_argument("--quarter", required=True, type=int, choices=[1, 2, 3, 4])
    p.add_argument("--states", required=True, nargs="+",
                    help="Used as BOTH rows and columns, e.g. oh pa az")
    p.add_argument("--version", default=None,
                    help="Trained version to use for every row's model (default: latest existing, per row)")
    p.add_argument("--out-dir", default=None,
                    help="Default: ./out_cross_state/<year>q<quarter>_<variable>")
    p.add_argument("--bootstrap-iters", type=int, default=0,
                    help="Bootstrap resamples per cell for a CI around that cell's R^2 "
                         "(default 0: skip bootstrapping entirely)")
    p.add_argument("--ci", type=float, default=0.95, help="Bootstrap CI width (default 0.95)")
    p.add_argument("--seed", type=int, default=1337, help="Bootstrap RNG seed")
    args = p.parse_args()

    states = [s.lower() for s in args.states]
    registry = load_registry()

    r2, n_pairs, bootstrap_df = build_matrix(
        args.variable, args.year, args.quarter, states, args.version, registry,
        bootstrap_iters=args.bootstrap_iters, ci=args.ci, seed=args.seed,
    )
    penalty = compute_transfer_penalty(r2)

    out_dir = Path(args.out_dir or f"./out_cross_state/{args.year}q{args.quarter}_{args.variable}")
    out_dir.mkdir(parents=True, exist_ok=True)
    r2.to_csv(out_dir / "r2_matrix.csv")
    n_pairs.to_csv(out_dir / "n_matrix.csv")
    penalty.to_csv(out_dir / "geographic_transfer_penalty_matrix.csv")
    print(f"Wrote {out_dir / 'r2_matrix.csv'}, n_matrix.csv, geographic_transfer_penalty_matrix.csv")

    if args.bootstrap_iters > 0:
        boot_path = out_dir / "r2_bootstrap.csv"
        bootstrap_df.to_csv(boot_path, index=False)
        print(f"Wrote {boot_path} ({len(bootstrap_df)} cell(s), {args.bootstrap_iters} "
              f"iters/cell, {int(args.ci * 100)}% CI)")

    plot_matrix(r2, args.year, args.quarter, args.variable, str(out_dir / "r2_matrix.png"))


if __name__ == "__main__":
    main()
