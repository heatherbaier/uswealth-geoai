"""
Alternative to amplitude_predictions.py (step 1 of the seasonal-amplitude
pipeline) for the case where predictions were already generated by hand
per model, instead of needing a fresh inference run. Walks an existing
tree of per-model "*_preds.csv" files (the same artifacts/<run>/epoch*
layout validation.ipynb and analyze_pixel_diversity_accuracy.py's
discover_quarters() already read elsewhere in this project) and reshapes
them into exactly the long table compute_amplitude.py (step 2) expects --
no model loading, no GPU, no sail import.

Expected layout (confirmed against a real file):
    <root>/q<model_quarter>_<model_year>_s2_allbands/artifacts/
        <state>_q<model_quarter>_<model_year>_<variable>_v<version>/
            epoch<N>[_valset]_<state>_<eval_year>_q<eval_quarter>_s2_allbands_<variable>_preds.csv
e.g.
    .../q1_2016_s2_allbands/artifacts/oh_q1_2016_wealth_index_v1/
        epoch195_valset_oh_2016_q1_s2_allbands_wealth_index_preds.csv
  -- model identity (model_year=2016, model_quarter=1, variable=wealth_index,
     version=1) comes from the enclosing run folder's name; eval identity
     (eval_year=2016, eval_quarter=1) and epoch come from the filename
     itself, which is what lets one run folder hold predictions against
     MULTIPLE eval quarters (the full off-diagonal grid), not just the
     model's own quarter. "_valset_" is optional in the filename (seen
     both with and without it elsewhere in this project) and is not used
     to decide diagonal vs. off-diagonal -- that's decided later, by
     compute_amplitude.py, from eval_year/eval_quarter vs. model_year/
     model_quarter.

Each matched CSV needs "name" (chip path -- GEOID is Path(name).stem,
normalized the same way everywhere else in this project), "pred", and
"label" columns; anything else (e.g. an "extra" column) is ignored.

If more than one epoch's preds file exists for the same (model, eval)
cell, only the highest epoch is kept (same "latest checkpoint wins"
convention band_importance.py's load_model_wrapper uses) -- with a
printed note so a run folder that was re-evaluated after more training
doesn't silently double-count that cell.

Output: identical format/columns to amplitude_predictions.py's output,
so compute_amplitude.py works completely unchanged on it --
    <out-dir>/<state>_<variable>_amplitude_predictions.csv

Usage:
    python 3_analysis/collect_existing_predictions.py --root /data/hbaier/new_data/tlag/oh_imagery \
        --state oh --variable wealth_index
"""

import argparse
import re
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "1_data_prep"))
from update_ys_labels import normalize_geoid  # noqa: E402

RUN_DIR_RE = re.compile(r"^(?P<state>[a-zA-Z]{2})_q(?P<model_quarter>\d)_(?P<model_year>\d{4})_"
                         r"(?P<variable>.+)_v(?P<version>\d+)$")
PREDS_FILE_RE = re.compile(r"^epoch(?P<epoch>\d+)_(?:valset_)?(?P<state>[a-zA-Z]{2})_(?P<eval_year>\d{4})_"
                            r"q(?P<eval_quarter>\d)_s2_allbands_(?P<variable>.+)_preds\.csv$")


def find_preds_files(root: Path):
    """Yields (path, parsed_run_dict, parsed_file_dict) for every preds
    CSV under root whose enclosing run folder AND filename both parse --
    anything that doesn't match either pattern is skipped with a printed
    reason, not guessed at."""
    for path in sorted(root.glob("**/artifacts/*/epoch*_preds.csv")):
        run_match = RUN_DIR_RE.match(path.parent.name)
        if not run_match:
            print(f"  skip {path}: run folder '{path.parent.name}' doesn't match "
                  f"<state>_q<quarter>_<year>_<variable>_v<version>")
            continue
        file_match = PREDS_FILE_RE.match(path.name)
        if not file_match:
            print(f"  skip {path}: filename doesn't match "
                  f"epoch<N>[_valset]_<state>_<year>_q<quarter>_s2_allbands_<variable>_preds.csv")
            continue
        yield path, run_match.groupdict(), file_match.groupdict()


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--root", required=True, type=Path,
                    help="State imagery root containing q<quarter>_<year>_s2_allbands/artifacts/... "
                         "(searched recursively)")
    p.add_argument("--state", required=True)
    p.add_argument("--variable", default="wealth_index")
    p.add_argument("--out-dir", default="3_analysis/outputs/amplitude", type=Path)
    args = p.parse_args()

    state = args.state.lower()
    root = args.root
    if not root.exists():
        raise SystemExit(f"--root {root} does not exist")

    # cell_key -> (epoch, path, run_info, file_info) -- keep only the
    # highest-epoch file per (model_year, model_quarter, eval_year, eval_quarter).
    best_per_cell = {}
    n_scanned = 0
    n_wrong_state_or_variable = 0

    for path, run_info, file_info in find_preds_files(root):
        n_scanned += 1
        if run_info["state"].lower() != state or file_info["state"].lower() != state:
            n_wrong_state_or_variable += 1
            continue
        if run_info["variable"] != args.variable or file_info["variable"] != args.variable:
            n_wrong_state_or_variable += 1
            continue

        cell_key = (int(run_info["model_year"]), int(run_info["model_quarter"]),
                    int(file_info["eval_year"]), int(file_info["eval_quarter"]))
        epoch = int(file_info["epoch"])

        prev = best_per_cell.get(cell_key)
        if prev is None or epoch > prev[0]:
            if prev is not None:
                print(f"  {cell_key}: epoch{epoch} supersedes epoch{prev[0]} ({path.name})")
            best_per_cell[cell_key] = (epoch, path)

    print(f"\nScanned {n_scanned} preds CSV(s) under {root} "
          f"({n_wrong_state_or_variable} skipped for wrong state/variable), "
          f"{len(best_per_cell)} unique (model, eval) cell(s) kept")
    if not best_per_cell:
        raise SystemExit("No matching preds CSVs found -- check --root/--state/--variable, or that the "
                          "run-folder/filename patterns documented in this script's own docstring "
                          "actually match what's on disk.")

    all_rows = []
    for (model_year, model_quarter, eval_year, eval_quarter), (epoch, path) in sorted(best_per_cell.items()):
        df = pd.read_csv(path)
        missing = {"name", "pred", "label"} - set(df.columns)
        if missing:
            print(f"  skip {path}: missing columns {missing}")
            continue
        for row in df.itertuples(index=False):
            all_rows.append({
                "state": state, "GEOID": normalize_geoid(Path(row.name).stem),
                "model_year": model_year, "model_quarter": model_quarter,
                "eval_year": eval_year, "eval_quarter": eval_quarter,
                "pred": float(row.pred), "label": float(row.label),
            })
        print(f"  [{model_year} Q{model_quarter} model -> eval {eval_year} Q{eval_quarter}] "
              f"epoch{epoch}: {len(df)} rows from {path}")

    if not all_rows:
        raise SystemExit("Every matched cell was missing required columns -- nothing to write.")

    out_df = pd.DataFrame(all_rows)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    out_path = args.out_dir / f"{state}_{args.variable}_amplitude_predictions.csv"
    out_df.to_csv(out_path, index=False)
    print(f"\nWrote {out_path} ({len(out_df):,} rows, "
          f"{out_df[['model_year', 'model_quarter', 'eval_year', 'eval_quarter']].drop_duplicates().shape[0]} cells, "
          f"{out_df['GEOID'].nunique():,} unique GEOIDs)")


if __name__ == "__main__":
    main()
