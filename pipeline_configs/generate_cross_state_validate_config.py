"""
Cross-state generalization: for one already-trained model
(--model-state/--model-year/--model-quarter/--variable), generate a
`task: validate` config (+ SLURM job) evaluating it against one or more
OTHER states' imagery (--imagery-states) -- same quarter/year by default,
so the only thing that changes between cells is geography, isolating the
"geographic transfer penalty" the same way generate_cross_validate_config.py
isolates the "seasonal transfer penalty" by holding state fixed and
varying quarter.

Why this does NOT reuse generate_cross_validate_config.py's "restrict to
the model's own held-out test set" mechanism, and uses the model's FULL
imagery dataset for every cross-state cell instead:

That mechanism works for cross-QUARTER because a state's stable/spatial
split (sail's splitting.py, split_strategy: stable) makes an item's
train/val/test bucket a pure function of its own GEOID (or spatial block)
+ seed -- not of which quarter's dataset it's loaded from. So the SAME
GEOID appears, in the SAME held-out bucket, in every quarter of that
state's imagery, and sail's run_validation (dataset.new=False) can
intersect the model's own test_indices.txt against a different quarter's
item list and get a real, leak-free overlap.

GEOIDs are census-tract identifiers, state-specific (state+county+tract
FIPS) by construction -- an Ohio GEOID never appears in Pennsylvania's
tract layout, full stop. Intersecting an Ohio model's test_indices.txt
against Pennsylvania's item list would always come back EMPTY (see sail's
adapters.py JSONGeoAdapter: validate+not-new intersects on item_key, the
basename stem) -- not an error, just a silent empty dataset / empty
predictions CSV. There is no "this model's held-out GEOIDs, as they'd
appear in another state" to restrict to, because that set doesn't exist.

That turns out not to matter here the way it would for cross-quarter:
restricting to held-out items is about avoiding leakage from THIS model's
own train/val set, and an Ohio-trained model never saw a single
Pennsylvania chip during training, full stop, regardless of which PA
items you evaluate it on. So every cell this script generates uses
dataset.new=True (sail's "validate against a completely different
dataset" mode -- see generate_validate_config.py's docstring) against
the FULL target state's available imagery for that quarter: leak-free
regardless, and more statistical power than an artificially restricted
subset would give.

One real consequence: the DIAGONAL cell (a state's own model evaluated
on its own imagery) is NOT generated by this script at all -- under
dataset.new=True it would include that model's own train/val chips,
making its R^2 an inflated, leaky "baseline" that isn't comparable to
every off-diagonal cell's honestly-held-out R^2. 3_validation/validate.py
/ generate_validate_config.py already produce the correct leak-free
diagonal (test-only, dataset.new=False) for every state; the row-builder
below (3_analysis/build_cross_state_r2_matrix.py) reads THAT for the
diagonal and this script's cross_state/ output for everything off it.
Passing --model-state as one of --imagery-states (with matching
--imagery-year/--imagery-quarter) is rejected for exactly this reason.

band_mean/band_std/in_channels in every generated config come from the
MODEL's (source) state's state_registry.yml entry, not the target
imagery state's -- the model was trained to expect ITS OWN state's
normalization statistics, and renormalizing the target imagery to the
target state's own stats would confound "does this model's learned
representation transfer to new geography" (the actual question) with "what
happens if you also feed it inputs scaled differently than anything it
was trained on" (a different, uninteresting question). This is the same
reasoning sail's SwinRegressor applies at the architecture level
(_expand_patch_embed_conv warm-starts new bands from the pretrained RGB
mean rather than discarding pretrained weights) -- keep the model's own
calibration, change only what's actually being tested.

Usage:
    # OH's Q1 2016 model, evaluated on PA and AZ's Q1 2016 imagery:
    python pipeline_configs/generate_cross_state_validate_config.py \
        --model-state oh --variable wealth_index \
        --model-year 2016 --model-quarter 1 \
        --imagery-states pa az --launch

    # Same model, evaluated against a different state's DIFFERENT quarter
    # too (rarely what you want -- this confounds geography with season
    # again -- but available if you have a specific reason):
    python pipeline_configs/generate_cross_state_validate_config.py \
        --model-state oh --variable wealth_index \
        --model-year 2016 --model-quarter 1 \
        --imagery-states pa --imagery-year 2017 --imagery-quarter 3

Run this once per already-trained model x target-state (looping
--model-state/--model-year/--model-quarter yourself, e.g. from a shell
loop, with --imagery-states set to every OTHER trained state) to build up
a full grid; then use 3_analysis/build_cross_state_r2_matrix.py to
assemble the resulting CSVs into the R^2 matrix, and
3_analysis/analyze_cross_state_significance.py to test each cell against
that target state's own diagonal baseline.
"""

import argparse
import os
import subprocess
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from generate_train_config import (  # noqa: E402
    PROJECT_ROOT, TARGET_CHOICES,
    load_registry, resolve_state_settings, write_job_file,
)
from generate_validate_config import latest_existing_version  # noqa: E402

# Subfolder (under the model's own ckpt_dir) every cross-state prediction
# CSV lands in -- mirrors generate_cross_validate_config.py's
# CROSS_QUARTER_SUBDIR, kept as a SEPARATE name/folder so a model that's
# been both cross-quarter- and cross-state-validated doesn't mix the two
# kinds of predictions together. build_cross_state_r2_matrix.py imports
# this rather than hardcoding it a second time.
CROSS_STATE_SUBDIR = "cross_state"


def build_config(model_state, variable, model_year, model_quarter,
                  imagery_state, imagery_year, imagery_quarter,
                  version, device, registry):
    model_st = resolve_state_settings(model_state, registry)

    model_data_root = model_st["data_root_template"].format(
        state=model_state, year=model_year, quarter=model_quarter)
    model_data_root = model_data_root if model_data_root.endswith("/") else model_data_root + "/"
    model_output_dir = model_data_root + "artifacts/"

    exp_base = f"{model_state}_q{model_quarter}_{model_year}_{variable}"
    version = version or latest_existing_version(model_output_dir, exp_base)
    experiment_name = f"{exp_base}_{version}"

    imagery_st = resolve_state_settings(imagery_state, registry)
    imagery_data_root = imagery_st["data_root_template"].format(
        state=imagery_state, year=imagery_year, quarter=imagery_quarter)
    imagery_data_root = imagery_data_root if imagery_data_root.endswith("/") else imagery_data_root + "/"
    imagery_base_prefix = imagery_st["base_prefix_template"].format(
        state=imagery_state, year=imagery_year, quarter=imagery_quarter)
    imagery_prefix = f"{imagery_base_prefix}_{variable}"

    cfg = {
        "task": "validate",
        # output_dir/experiment_name identify the MODEL: which checkpoint
        # gets loaded, where the output CSV is written. test_indices.txt
        # under here is NOT used (dataset.new=True below) -- see module
        # docstring for why a cross-state cell can't use it.
        "experiment_name": experiment_name,
        "output_dir": model_output_dir,
        "dataset": {
            "type": "json",
            "data_root": imagery_data_root,
            "prefix": imagery_prefix,
            "img_size": [256, 256],
            "num_workers": 0,
            "seed": 1337,
            "temporal": False,
            # True ("validate against a completely different dataset" --
            # generate_validate_config.py's docstring): evaluates the
            # FULL imagery_state dataset, no test_indices.txt
            # intersection. See module docstring -- the model's own
            # held-out set doesn't exist in another state's GEOID space,
            # but it's also unnecessary: this model never saw ANY of
            # imagery_state's chips during training, so there's no
            # leakage to guard against regardless of which of its items
            # get evaluated.
            "new": True,
            # The MODEL's own (source-state) normalization stats, not
            # imagery_state's -- see module docstring.
            "band_mean": model_st["band_mean"],
            "band_std": model_st["band_std"],
        },
        "model": {
            "name": "swin",
            # in_channels must also match what the model was actually
            # trained/built with -- the model's own state, same reasoning
            # as band_mean/band_std above.
            "params": {"in_channels": model_st["in_channels"]},
        },
        "validator": {
            "device": device,
            # Keep every cross-state prediction CSV in its own subfolder
            # under the model's ckpt_dir -- separate from this model's
            # normal single-quarter validate output (no output_subdir)
            # AND from any cross-quarter output (CROSS_QUARTER_SUBDIR in
            # generate_cross_validate_config.py). Needs sail PR #25.
            "output_subdir": CROSS_STATE_SUBDIR,
        },
    }
    return cfg, experiment_name, imagery_prefix


def main():
    p = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--model-state", required=True, help="State the already-trained model was trained on")
    p.add_argument("--variable", required=True, choices=TARGET_CHOICES)
    p.add_argument("--model-year", required=True, type=int)
    p.add_argument("--model-quarter", required=True, type=int, choices=[1, 2, 3, 4])
    p.add_argument("--imagery-states", required=True, nargs="+",
                    help="One or more OTHER states' imagery to evaluate this model against "
                         "(must differ from --model-state at the same --imagery-year/"
                         "--imagery-quarter -- see module docstring for why that 'diagonal' "
                         "cell isn't generated here)")
    p.add_argument("--imagery-year", type=int, default=None,
                    help="Default: same as --model-year (holds year fixed, varies only state)")
    p.add_argument("--imagery-quarter", type=int, choices=[1, 2, 3, 4], default=None,
                    help="Default: same as --model-quarter (holds season fixed, isolating pure "
                         "geographic transfer -- override only if you have a specific reason to "
                         "also vary season, which confounds the two effects)")
    p.add_argument("--version", default=None,
                    help="Which trained v<N> of the model to evaluate. Default: latest existing")
    p.add_argument("--device", default="cuda")
    p.add_argument("--out-dir", default=None,
                    help="Default: configs/sail/tlags/<model-state>/cross_state/")
    p.add_argument("--no-job-file", action="store_true", help="Skip writing SLURM job files")
    p.add_argument("--nodes", default="1")
    p.add_argument("--gpus", default="1")
    p.add_argument("--cpus", default="8")
    p.add_argument("--walltime", default="24:00:00")
    p.add_argument("--partition", default="general")
    p.add_argument("--qos", default="grp_hbaier")
    p.add_argument("--conda-env", default="geomain")
    p.add_argument("--repo-dir", default="/home/hbaier/packages/uswealth-geoai",
                    help="Working directory the SLURM job cd's into -- this project repo, "
                         "not sail (sail is used as an installed command, not by path)")
    p.add_argument("--launch", action="store_true",
                    help="sbatch each job file immediately after writing it (requires job files)")
    args = p.parse_args()

    model_state = args.model_state.lower()
    imagery_year = args.imagery_year if args.imagery_year is not None else args.model_year
    imagery_quarter = args.imagery_quarter if args.imagery_quarter is not None else args.model_quarter

    registry = load_registry()
    out_dir = args.out_dir or os.path.join(
        PROJECT_ROOT, "configs", "sail", "tlags", model_state, "cross_state"
    )
    os.makedirs(out_dir, exist_ok=True)

    for imagery_state in args.imagery_states:
        imagery_state = imagery_state.lower()
        if (imagery_state, imagery_year, imagery_quarter) == (model_state, args.model_year, args.model_quarter):
            raise SystemExit(
                f"--imagery-states includes {imagery_state!r} at the same year/quarter as "
                f"--model-state {model_state!r} ({args.model_year} Q{args.model_quarter}) -- "
                f"that's this model evaluated on its OWN imagery under dataset.new=True, which "
                f"would include its own train/val chips (a leaky, inflated 'baseline', not a "
                f"real cross-state cell). Use 3_validation/validate.py's existing per-quarter "
                f"output for that state's leak-free diagonal instead -- "
                f"build_cross_state_r2_matrix.py already reads it for you."
            )

        cfg, experiment_name, imagery_prefix = build_config(
            model_state, args.variable, args.model_year, args.model_quarter,
            imagery_state, imagery_year, imagery_quarter,
            args.version, args.device, registry,
        )

        tag = f"{experiment_name}_on_{imagery_state}_{imagery_year}q{imagery_quarter}"
        out_path = os.path.join(out_dir, f"{tag}_validate.yml")
        with open(out_path, "w") as f:
            yaml.safe_dump(cfg, f, sort_keys=False)
        print(f"Wrote {out_path}")
        print(f"  model: {experiment_name} ({model_state.upper()})   "
              f"imagery: {imagery_state.upper()} {imagery_year} Q{imagery_quarter} ({imagery_prefix})")

        job_path = None
        if not args.no_job_file:
            job_path = os.path.join(out_dir, f"{tag}.sh")
            write_job_file(job_path, tag, out_path, args.nodes, args.gpus,
                            args.cpus, args.walltime, args.partition, args.qos,
                            args.conda_env, args.repo_dir)
            print(f"  Wrote {job_path}")

        if args.launch:
            if job_path is None:
                raise SystemExit("--launch requires job files -- drop --no-job-file")
            subprocess.run(["sbatch", job_path], check=True)


if __name__ == "__main__":
    main()
